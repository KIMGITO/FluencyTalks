// Runs after `vite build` and `vite build --ssr src/entry-server.tsx --outDir dist-ssr` (see package.json "build").
// Writes each public page as static HTML (dist/index.html, dist/blog.html, dist/blog/<slug>.html, ...) with its own
// <title>, description, canonical and social tags, and generates dist/sitemap.xml from the same list.
// Also writes dist/404.html and dist/app.html, the shell for logged-in routes.
// Cloudflare serves /blog from blog.html without a redirect, so canonical URLs have no trailing slash.
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const dist = path.join(root, 'dist');
const { render, PUBLIC_PAGES, tokenCss } = await import(pathToFileURL(path.join(root, 'dist-ssr', 'entry-server.js')).href);
const SITE = 'https://thefluencytalks.com';

const template = await fs.readFile(path.join(dist, 'index.html'), 'utf8');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function setMeta(html, attr, key, value) {
  const re = new RegExp(`(<meta ${attr}="${key}" content=")[^"]*(")`);
  if (!re.test(html)) throw new Error(`index.html has no <meta ${attr}="${key}">`);
  return html.replace(re, `$1${esc(value)}$2`);
}

function page(path_, html, seo) {
  if (!seo) throw new Error(`${path_} did not call useSeo()`);
  let out = template
    // The <noscript> summary is for the bare SPA shell; prerendered pages carry the real content.
    .replace(/\s*<!-- Fallback content[^]*?<\/noscript>/, '')
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(seo.title)}</title>`)
    .replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${esc(seo.url)}$2`)
    .replace('</head>', `<style id="ft-tokens">${tokenCss()}</style>\n  </head>`)
    // If Cloudflare's SPA fallback serves this file for another URL (e.g. /home), drop the prerendered
    // page before it paints so the app does not flash the wrong content.
    .replace('<div id="root"></div>', `<div id="root">${html}</div>\n    <script>if (location.pathname.replace(/\\/$/, '') !== ${JSON.stringify(path_.replace(/\/$/, ''))}) document.getElementById('root').innerHTML = '';</script>`);
  for (const [attr, key, value] of [
    ['name', 'title', seo.title], ['name', 'description', seo.description], ['name', 'robots', seo.robots],
    ['property', 'og:type', seo.type], ['property', 'og:url', seo.url], ['property', 'og:title', seo.title],
    ['property', 'og:description', seo.description], ['property', 'og:image', seo.image],
    ['name', 'twitter:url', seo.url], ['name', 'twitter:title', seo.title],
    ['name', 'twitter:description', seo.description], ['name', 'twitter:image', seo.image],
  ]) out = setMeta(out, attr, key, value);
  return out;
}

for (const { path: p } of PUBLIC_PAGES) {
  const { html, seo } = render(p);
  const file = p === '/' ? path.join(dist, 'index.html') : path.join(dist, `${p.slice(1)}.html`);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, page(p, html, seo));
  console.log(`prerendered ${p} -> ${path.relative(root, file)}`);
}

// Unknown URLs get this with a real 404 status (wrangler.toml). The app still boots on it and shows its own 404 page.
{
  const { html, seo } = render('/404');
  await fs.writeFile(path.join(dist, '404.html'), page('/404', html, seo));
}
// App and sign-in URLs get this bare shell (public/_redirects): the unrendered template, kept out of search.
await fs.writeFile(path.join(dist, 'app.html'), setMeta(template, 'name', 'robots', 'noindex, nofollow')
  .replace('</head>', `<style id="ft-tokens">${tokenCss()}</style>\n  </head>`));

const urls = PUBLIC_PAGES.map(({ path: p, priority, changefreq, lastmod }) =>
  `  <url><loc>${SITE}${p === '/' ? '/' : p}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ''}<changefreq>${changefreq}</changefreq><priority>${priority.toFixed(1)}</priority></url>`);
await fs.writeFile(path.join(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <!-- Generated by scripts/prerender.mjs from PUBLIC_PAGES in src/entry-server.tsx. -->\n${urls.join('\n')}\n</urlset>\n`);
console.log(`sitemap.xml: ${urls.length} URLs`);

// The Supabase client in the SSR bundle can keep timers alive.
process.exit(0);
