#!/usr/bin/env node
// Regenerates src/lib/tzCountry.generated.ts from the IANA time zone database.
//
//   curl -O https://raw.githubusercontent.com/eggert/tz/main/zone1970.tab
//   node scripts/gen-tz-country.mjs [path/to/zone1970.tab]
//
// zone1970.tab is the canonical zone -> country reference; it is the same data the
// runtime resolves, so the map cannot drift from what the user's browser reports.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tab = process.argv[2] ?? resolve(process.cwd(), 'zone1970.tab');

/** zone -> ISO alpha-2. A zone may list several countries (Asia/Dubai -> AE,OM,RE,SC,TF): first wins. */
const map = {};
for (const line of readFileSync(tab, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [codes, , zone] = line.split('\t');
  if (!zone || codes === '-') continue;
  const code = codes.split(',')[0]?.trim();
  if (!code || !/^[A-Z]{2}$/.test(code)) continue;
  if (!map[zone]) map[zone] = code;
}
const zones = Object.keys(map).sort();

// Six pairs per line keeps the generated file readable in diffs.
const rows = [];
for (let i = 0; i < zones.length; i += 6) {
  rows.push('  ' + zones.slice(i, i + 6).map((z) => `${JSON.stringify(z)}: ${JSON.stringify(map[z])}`).join(', ') + ',');
}

const out = `// GENERATED by scripts/gen-tz-country.mjs from the IANA tz database (zone1970.tab).
// IANA zone -> ISO 3166-1 alpha-2. Zones listing several countries (Asia/Dubai -> AE,OM,RE,SC,TF)
// map to the first, and zones with no country code at all (Factory) are left out.
// Used to serve a country from the timezone until the user picks one explicitly.
export const TZ_COUNTRY: Record<string, string> = {
${rows.join('\n')}
};
`;

writeFileSync(resolve(root, 'src/lib/tzCountry.generated.ts'), out);
console.log(`${zones.length} zones -> src/lib/tzCountry.generated.ts`);